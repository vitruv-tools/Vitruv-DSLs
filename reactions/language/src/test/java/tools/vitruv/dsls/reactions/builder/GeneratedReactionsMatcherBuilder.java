package tools.vitruv.dsls.reactions.builder;

import com.google.common.io.CharStreams;
import com.google.inject.Inject;
import com.google.inject.Provider;
import java.io.IOException;
import java.io.InputStreamReader;
import java.io.Reader;
import java.io.UncheckedIOException;
import java.util.Arrays;
import java.util.Map;
import java.util.Optional;
import java.util.function.Consumer;
import org.eclipse.emf.common.util.URI;
import org.eclipse.xtext.generator.InMemoryFileSystemAccess;
import org.eclipse.xtext.resource.XtextResourceSet;
import org.eclipse.xtext.testing.util.ParseHelper;
import org.hamcrest.Description;
import org.hamcrest.Matcher;
import org.hamcrest.TypeSafeMatcher;
import tools.vitruv.dsls.reactions.api.generator.IReactionsGenerator;
import tools.vitruv.dsls.reactions.language.toplevelelements.ReactionsFile;

/**
 * A matcher checking reactions generated by a {@link FluentReactionsFileBuilder}. See {@link
 * #builds} for details.
 */
public class GeneratedReactionsMatcherBuilder {
  private static final URI SYNTHETIC =
      URI.createHierarchicalURI("synthetic", null, null, new String[0], null, null);

  @Inject
  private ParseHelper<ReactionsFile> parseHelper;
  @Inject
  private Provider<IReactionsGenerator> generatorProvider;
  @Inject
  private Provider<InMemoryFileSystemAccess> inMemoryFileSystemAccessProvider;
  @Inject
  private Provider<XtextResourceSet> resourceSetProvider;

  private static class GeneratedReactionsMatcher extends TypeSafeMatcher<FluentReactionsFileBuilder> {
    private final GeneratedReactionsMatcherBuilder generatedReactions;
    private final String expectedReaction;
    private Consumer<Description> mismatch;

    GeneratedReactionsMatcher(
        GeneratedReactionsMatcherBuilder generatedReactions, String expectedReaction) {
      this.generatedReactions = generatedReactions;
      this.expectedReaction = expectedReaction;
    }

    @Override
    protected boolean matchesSafely(FluentReactionsFileBuilder item) {
      IReactionsGenerator generator = generatedReactions.generatorProvider.get();
      InMemoryFileSystemAccess fsa = generatedReactions.inMemoryFileSystemAccessProvider.get();
      generator.useResourceSet(generatedReactions.resourceSetProvider.get());
      generator.addReactionsFile(item);
      try {
        generator.writeReactions(fsa);
      } catch (IOException e) {
        throw new UncheckedIOException(e);
      }

      if (!hasSingleGeneratedFile(fsa)) {
        return false;
      }
      String serializationResult = getSingleGeneratedFileContent(fsa);
      if (!isEqual(expectedReaction, serializationResult)) {
        return false;
      }

      Map<String, CharSequence> expectedGeneratedCodeFileNamesToContents =
          generateCodeFiles(expectedReaction);
      Map<String, CharSequence> actualGeneratedCodeFileNamesToContents =
          generateCodeFiles(serializationResult);

      return areEqual(
          expectedGeneratedCodeFileNamesToContents, actualGeneratedCodeFileNamesToContents);
    }

    private boolean hasSingleGeneratedFile(InMemoryFileSystemAccess fsa) {
      if (fsa.getAllFiles().size() != 1) {
        if (fsa.getAllFiles().isEmpty()) {
          mismatch = description -> description.appendText("serializing the builder had no results");
        } else {
          mismatch =
              description ->
                  description
                      .appendText("serializing the builder had more than one result: ")
                      .appendValueList("[", ", ", "]", fsa.getAllFiles().keySet());
        }
        return false;
      }
      return true;
    }

    private String getSingleGeneratedFileContent(InMemoryFileSystemAccess fsa) {
      return read(fsa, fsa.getAllFiles().keySet().iterator().next());
    }

    private boolean isEqual(String expectedReactionsCode, String generatedReactionsCode) {
      if (!equalsIgnoringWhitespace(expectedReactionsCode, generatedReactionsCode)) {
        mismatch =
            description ->
                appendFirstMismatchLineIgnoringWhitespace(
                    description
                        .appendText(
                            "serializing the builder resulted in a different reactions file:\n\n")
                        .appendText(generatedReactionsCode)
                        .appendText("\n\nFirst mismatching line:\n\n"),
                    generatedReactionsCode,
                    expectedReactionsCode);
        return false;
      }
      return true;
    }

    private Map<String, CharSequence> generateCodeFiles(String reactionsCode) {
      XtextResourceSet resourceSet = generatedReactions.resourceSetProvider.get();
      try {
        generatedReactions.parseHelper.parse(
            reactionsCode,
            SYNTHETIC.appendSegment("reaction").appendFileExtension("reactions"),
            resourceSet);
      } catch (Exception e) {
        throw new IllegalStateException("could not parse reactions code", e);
      }
      InMemoryFileSystemAccess fsa = generatedReactions.inMemoryFileSystemAccessProvider.get();
      IReactionsGenerator generator = generatedReactions.generatorProvider.get();
      generator.addReactionsFiles(resourceSet);
      generator.generate(fsa);
      return fsa.getTextFiles();
    }

    private boolean areEqual(
        Map<String, CharSequence> expectedGeneratedCodeFileNamesToContents,
        Map<String, CharSequence> actualGeneratedCodeFileNamesToContents) {
      Optional<String> unexpectedItemFile =
          actualGeneratedCodeFileNamesToContents.keySet().stream()
              .filter(file -> !expectedGeneratedCodeFileNamesToContents.containsKey(file))
              .findFirst();
      if (unexpectedItemFile.isPresent()) {
        mismatch =
            description ->
                description
                    .appendText("generating from the builder produced the unexpected file ")
                    .appendValue(unexpectedItemFile.get());
        return false;
      }
      expectedGeneratedCodeFileNamesToContents.keySet().stream()
          .filter(file -> !actualGeneratedCodeFileNamesToContents.containsKey(file))
          .findFirst()
          .ifPresent(
              missingItemFile ->
                  mismatch =
                      description ->
                          description
                              .appendText(
                                  "generating from the builder did not produce the expected file ")
                              .appendValue(missingItemFile));
      for (String filePath : expectedGeneratedCodeFileNamesToContents.keySet()) {
        String expectedContent = expectedGeneratedCodeFileNamesToContents.get(filePath).toString();
        String itemContent = actualGeneratedCodeFileNamesToContents.get(filePath).toString();
        if (!equalsIgnoringWhitespace(expectedContent, itemContent)) {
          mismatch =
              description ->
                  appendFirstMismatchLineIgnoringWhitespace(
                      description
                          .appendText("generating from the builder produced wrong content for ")
                          .appendValue(filePath)
                          .appendText(".\nExpected was:\n\n")
                          .appendText(expectedContent)
                          .appendText("\n\n But got:\n\n")
                          .appendText(itemContent)
                          .appendText("\n\nFirst mismatching line:\n\n"),
                      itemContent,
                      expectedContent);
          return false;
        }
      }
      return true;
    }

    @Override
    public void describeTo(Description description) {
      description
          .appendText("a reactions file builder producing this reactions file: \n\n")
          .appendText(expectedReaction);
    }

    @Override
    protected void describeMismatchSafely(
        FluentReactionsFileBuilder item, Description mismatchDescription) {
      if (mismatch != null) {
        mismatch.accept(mismatchDescription);
      }
    }
  }

  /**
   * Created a matcher for a {@link FluentReactionsFileBuilder}. The matcher checks that the builder
   * builds the given {@code expectedReaction}. It does this in two ways: By comparing the
   * serialized builder result with the {@code expectedReaction}, and by generating Java code for
   * both and comparing that code.
   *
   * <p>The reaction code is compared ignoring whitespace, the generated Java code is compared
   * character by character.
   */
  public Matcher<? super FluentReactionsFileBuilder> builds(String expectedReaction) {
    return new GeneratedReactionsMatcher(this, expectedReaction);
  }

  /** Tries to build the provided {@code builder}, without any further checks. */
  public void build(FluentReactionsFileBuilder builder) {
    IReactionsGenerator generator = generatorProvider.get();
    InMemoryFileSystemAccess fsa = inMemoryFileSystemAccessProvider.get();
    generator.useResourceSet(resourceSetProvider.get());
    generator.addReactionsFile(builder);
    generator.generate(fsa);
  }

  private static String read(InMemoryFileSystemAccess fsa, String path) {
    try (Reader reader = new InputStreamReader(fsa.readBinaryFile(path, ""))) {
      return CharStreams.toString(reader);
    } catch (IOException e) {
      throw new UncheckedIOException(e);
    }
  }

  private static String withoutWhitespace(String s) {
    return s.replaceAll("\\s+", "");
  }

  private static boolean equalsIgnoringWhitespace(String a, String b) {
    return withoutWhitespace(a).equals(withoutWhitespace(b));
  }

  private static void appendFirstMismatchLineIgnoringWhitespace(
      Description description, String mismatch, String reference) {
    firstMismatchLineIgnoringWhitespace(mismatch, reference)
        .ifPresentOrElse(description::appendValue, () -> description.appendValue(null));
  }

  private static Optional<String> firstMismatchLineIgnoringWhitespace(
      String mismatch, String reference) {
    String[] mismatchLines = mismatch.split(System.lineSeparator());
    return getFirstLineNotContainedInReferenceText(mismatchLines, reference)
        .or(
            () -> {
              String[] referenceLines = reference.split(System.lineSeparator());
              return getFirstLineNotContainedInReferenceText(referenceLines, mismatch);
            });
  }

  private static Optional<String> getFirstLineNotContainedInReferenceText(
      String[] lines, String reference) {
    String referenceWithoutWhitespace = withoutWhitespace(reference);
    return Arrays.stream(lines)
        .filter(line -> !referenceWithoutWhitespace.contains(withoutWhitespace(line)))
        .findFirst();
  }
}
