package tools.vitruv.dsls.reactions.builder;

import allElementTypes.AllElementTypesPackage;
import allElementTypes2.AllElementTypes2Package;
import jakarta.inject.Inject;
import java.io.IOException;
import java.io.InputStream;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.util.Arrays;
import org.eclipse.emf.common.util.EList;
import org.eclipse.emf.ecore.EClass;
import org.eclipse.emf.ecore.EcorePackage;
import org.eclipse.xtext.common.types.JvmFormalParameter;
import org.eclipse.xtext.common.types.JvmIdentifiableElement;
import org.eclipse.xtext.common.types.TypesFactory;
import org.eclipse.xtext.testing.InjectWith;
import org.eclipse.xtext.testing.extensions.InjectionExtension;
import org.eclipse.xtext.xbase.XAssignment;
import org.eclipse.xtext.xbase.XBinaryOperation;
import org.eclipse.xtext.xbase.XBlockExpression;
import org.eclipse.xtext.xbase.XExpression;
import org.eclipse.xtext.xbase.XForLoopExpression;
import org.eclipse.xtext.xbase.XListLiteral;
import org.eclipse.xtext.xbase.XNumberLiteral;
import org.eclipse.xtext.xbase.XStringLiteral;
import org.eclipse.xtext.xbase.XbaseFactory;
import org.hamcrest.Matcher;
import org.junit.jupiter.api.extension.ExtendWith;
import tools.vitruv.dsls.reactions.tests.ReactionsLanguageInjectorProvider;

/**
 * Base class for testing the {@link FluentReactionsLanguageBuilder}.
 *
 * <p>Provides constructor methods for various {@link XExpression}s that are used
 * within the builder tests.
 */
@ExtendWith(InjectionExtension.class)
@InjectWith(ReactionsLanguageInjectorProvider.class)
public abstract class FluentReactionsBuilderTest {
  private static final String RESOURCE_DIRECTORY =
      "/tools/vitruv/dsls/reactions/tests/buildertests/";

  /** The {@link EClass} {@code allElementTypes::Root}. */
  protected static final EClass Root = AllElementTypesPackage.eINSTANCE.getRoot();
  /** The {@link EClass} {@code allElementTypes::NonRoot}. */
  protected static final EClass NonRoot = AllElementTypesPackage.eINSTANCE.getNonRoot();
  /** The {@link EClass} {@code allElementTypes2::Root2}. */
  protected static final EClass Root2 = AllElementTypes2Package.eINSTANCE.getRoot2();
  /** The {@link EClass} {@code ecore::EObject}. */
  protected static final EClass EObject = EcorePackage.eINSTANCE.getEObject();

  /** Creates the matchers that check the reactions generated by a builder. */
  @Inject
  protected GeneratedReactionsMatcherBuilder matcher;
  /** Entry point for building reactions files in the tests. */
  @Inject
  protected FluentReactionsLanguageBuilder create;

  /**
   * Constructs the {@link XAssignment} {@code feature = value}.
   *
   * @param feature {@link JvmIdentifiableElement}
   * @param value {@link XExpression}
   * @return {@link XAssignment}
   */
  protected static XAssignment assign(JvmIdentifiableElement feature, XExpression value) {
    XAssignment xAssignment = XbaseFactory.eINSTANCE.createXAssignment();
    xAssignment.setFeature(feature);
    xAssignment.setValue(value);
    return xAssignment;
  }

  /**
   * Constructs the {@link XNumberLiteral} with the numeric value {@code number}.
   *
   * @param number String
   * @return {@link XNumberLiteral}
   */
  protected static XNumberLiteral number(String number) {
    XNumberLiteral numberLiteral = XbaseFactory.eINSTANCE.createXNumberLiteral();
    numberLiteral.setValue(number);
    return numberLiteral;
  }

  /**
   * Constructs the {@link XStringLiteral} {@code "value"}.
   *
   * @param value {@link String}
   * @return {@link XStringLiteral}
   */
  protected static XStringLiteral stringLiteral(String value) {
    XStringLiteral stringLiteral = XbaseFactory.eINSTANCE.createXStringLiteral();
    stringLiteral.setValue(value);
    return stringLiteral;
  }

  /**
   * Constructs a binary operation of the form
   * {@code leftOperand operator rightOperand}.
   *
   * @param leftOperand {@link XExpression}
   * @param operator {@link JvmIdentifiableElement}
   * @param rightOperand {@link XExpression}
   * @return {@link XBinaryOperation}
   */
  protected static XBinaryOperation binaryOperation(
      XExpression leftOperand,
      JvmIdentifiableElement operator,
      XExpression rightOperand
  ) {
    XBinaryOperation binaryOperation = XbaseFactory.eINSTANCE.createXBinaryOperation();
    binaryOperation.setLeftOperand(leftOperand);
    binaryOperation.setFeature(operator);
    binaryOperation.setRightOperand(rightOperand);
    return binaryOperation;
  }

  /**
   * Constructs a formal parameter with the name {@code name}.
   *
   * @param name {@link String}
   * @return {@link JvmFormalParameter}
   */
  protected static JvmFormalParameter formalParameter(String name) {
    JvmFormalParameter formalParameter = TypesFactory.eINSTANCE.createJvmFormalParameter();
    formalParameter.setName(name);
    return formalParameter;
  }

  /**
   * Constructs a block expression {@code { expressions }} that contains all {@code expressions}.
   *
   * @param expressions {@link XExpression} array, empty for an empty block
   * @return {@link XBlockExpression}
   */
  protected static XBlockExpression block(XExpression... expressions) {
    XBlockExpression blockExpression = XbaseFactory.eINSTANCE.createXBlockExpression();
    EList<XExpression> blockExpressions = blockExpression.getExpressions();
    blockExpressions.addAll(Arrays.asList(expressions));
    return blockExpression;
  }

  /**
   * Constructs a list literal that holds all elements in {@code expressions}
   * as list elements.
   *
   * @param expressions {@link XExpression} array, empty for an empty literal
   * @return {@link XListLiteral}
   */
  protected static XListLiteral xtendListOf(XExpression... expressions) {
    XListLiteral list = XbaseFactory.eINSTANCE.createXListLiteral();
    EList<XExpression> blockExpressions = list.getElements();
    blockExpressions.addAll(Arrays.asList(expressions));
    return list;
  }

  /**
   * Constructs a for loop of the form {@code for (loopParameter : elementSource) body}.
   *
   * @param loopParameter {@link JvmFormalParameter} declared for each element
   * @param elementSource {@link XExpression} that provides the elements to iterate over
   * @param body {@link XExpression} that is executed for each element
   * @return {@link XForLoopExpression}
   */
  protected static XForLoopExpression forLoop(
      JvmFormalParameter loopParameter,
      XExpression elementSource,
      XExpression body
  ) {
    XForLoopExpression forLoop = XbaseFactory.eINSTANCE.createXForLoopExpression();
    forLoop.setDeclaredParam(loopParameter);
    forLoop.setForExpression(elementSource);
    forLoop.setEachExpression(body);
    return forLoop;
  }

  /**
   * Reads the expected reactions from a file in the {@code buildertests} resource directory.
   *
   * @param fileName {@link String} name of the reactions file, including the extension
   * @return {@link String} with the content of the file
   */
  protected static String readReactions(String fileName) {
    String path = RESOURCE_DIRECTORY + fileName;
    try (InputStream stream = FluentReactionsBuilderTest.class.getResourceAsStream(path)) {
      if (stream == null) {
        throw new IllegalArgumentException("Reactions file not found on the classpath: " + path);
      }
      return new String(stream.readAllBytes(), StandardCharsets.UTF_8);
    } catch (IOException e) {
      throw new UncheckedIOException(e);
    }
  }

  /**
   * Creates a {@link Matcher} that checks that a {@link FluentReactionsFileBuilder} builds the
   * reactions in {@code reactionsText}. See {@link GeneratedReactionsMatcherBuilder#builds} for
   * how the comparison is done.
   *
   * @param reactionsText {@link String} with the expected reactions file content
   * @return {@link Matcher}
   */
  protected Matcher<? super FluentReactionsFileBuilder> builds(String reactionsText) {
    return matcher.builds(reactionsText);
  }
}
